import { describe, expect, it, vi } from "vitest";
vi.mock("server-only", () => ({}));
import { withLiveLearningFixture } from "./live-fixture";
import { outcomePredictionDescriptor } from "@/domain/mechanic-families/v2/investigation";
import { prediction } from "../mechanics/investigation/fixtures";

const key = () => crypto.randomUUID();
describe.skipIf(process.env.LEARNING_RUNTIME_DB_TESTS !== "1")("real learning service rollback proof", () => {
  it("persists inputs and action identities, authenticates replays, preserves history and advances reading only explicitly", async () => {
    await withLiveLearningFixture(async ({ service, actor, program, tx }) => {
      const initial = await service.loadSession(actor, program.enrollmentId);
      expect(initial.activity).toBeNull();
      expect(initial.savedInput).toBeNull();
      expect(initial.enrollment.routeRevision).toBe(1);
      expect((await tx.query("SELECT id FROM unfurl.activity_sessions WHERE enrollment_id=$1", [program.enrollmentId])).rowCount).toBe(0);
      expect((await tx.query("SELECT lesson_id FROM unfurl.enrollment_lesson_traversal WHERE enrollment_id=$1", [program.enrollmentId])).rowCount).toBe(0);
      const advanceKey = key();
      const afterReading = await service.advance(actor, program.enrollmentId, { key: advanceKey, body: { expectedRouteRevision: 1 } });
      expect(afterReading.data.task?.id).toBe(program.tasks[2]!.task.id);
      expect(afterReading.data.enrollment.routeRevision).toBe(2);
      expect((await service.advance(actor, program.enrollmentId, { key: advanceKey, body: { expectedRouteRevision: 1 } })).data.enrollment.routeRevision).toBe(2);
      const task = afterReading.data.task!;
      const startKey = key();
      const started = await service.startActivity(actor, program.enrollmentId, { key: startKey, body: { taskId: task.id, taskVersion: 1 } });
      const activityId = started.data.activity.id;
      expect(started.data.savedInput).toBeNull();
      expect((await service.startActivity(actor, program.enrollmentId, { key: key(), body: { taskId: task.id, taskVersion: 1 } })).data.activity.id).toBe(activityId);
      const draft = { ...outcomePredictionDescriptor.createInitialResponse(prediction), interval: { lower: 7, upper: 7, unit: "unitless" as const } };
      const saveKey = key();
      const saved = await service.saveInput(actor, activityId, { key: saveKey, body: { expectedInputRevision: 0, response: draft } });
      expect(saved.data.activity.inputRevision).toBe(1);
      expect(saved.data.activity.revision).toBe(1);
      expect((await service.saveInput(actor, activityId, { key: saveKey, body: { expectedInputRevision: 0, response: draft } })).data.activity.inputRevision).toBe(1);
      await expect(service.saveInput(actor, activityId, { key: key(), body: { expectedInputRevision: 0, response: draft } })).rejects.toMatchObject({ status: 409 });
      await expect(service.saveInput(actor, activityId, { key: saveKey, body: { expectedInputRevision: 0, response: { ...draft, interval: { ...draft.interval, lower: 6 } } } })).rejects.toMatchObject({ code: "idempotency_conflict" });
      const foreign = { ...actor, id: key() };
      await expect(service.startActivity(foreign, program.enrollmentId, { key: startKey, body: { taskId: task.id, taskVersion: 1 } })).rejects.toMatchObject({ status: 404 });
      await expect(service.getActivity(foreign, activityId)).rejects.toMatchObject({ status: 404 });
      const action = { expectedRevision: 1, clientActionId: key(), inputRevision: 1, responseDigest: saved.data.savedInput!.responseDigest, action: { kind: "prediction.commit" as const } };
      const committed = await service.dispatchAction(actor, activityId, { key: key(), body: action });
      expect(committed.data.receipt.sessionRevision).toBe(2);
      expect(committed.data.activity.revision).toBe(3);
      expect(committed.data.activity.remainingActions).toBe(6);
      const replay = await service.dispatchAction(actor, activityId, { key: key(), body: action });
      expect(replay.data.receipt.id).toBe(committed.data.receipt.id);
      expect(replay.data.activity.events).toHaveLength(1);
      const runAnswer = { ...draft, commitReceiptId: committed.data.receipt.id };
      const runInput = await service.saveInput(actor, activityId, { key: key(), body: { expectedInputRevision: 1, response: runAnswer } });
      const runBody = { expectedRevision: 3, clientActionId: key(), inputRevision: 2, responseDigest: runInput.data.savedInput!.responseDigest, action: { kind: "run" as const } };
      const observed = await service.dispatchAction(actor, activityId, { key: key(), body: runBody });
      expect(observed.data.activity.remainingActions).toBe(5);
      expect(observed.data.receipt.sessionRevision).toBe(4);
      expect(observed.data.activity.revision).toBe(5);
      expect(observed.data.receipt.observation).toMatchObject({ kind: "values", values: [{ quantity: { value: 7 } }] });
      const retried = await service.retryAction(actor, activityId, observed.data.receipt.id, { key: key(), body: { expectedRevision: 1 } });
      expect(retried.data.activity.remainingActions).toBe(5);
      expect(retried.data.receipt).toEqual(observed.data.receipt);
      await service.saveInput(actor, activityId, { key: key(), body: { expectedInputRevision: 2, response: { ...runAnswer, observationReceiptId: observed.data.receipt.id } } });
      const loaded = await service.getActivity(actor, activityId);
      expect(loaded.savedInput?.inputRevision).toBe(3);
      expect(loaded.activity.events[1]!.receipt.input.inputRevision).toBe(2);
      await expect(service.advance(actor, program.enrollmentId, { key: key(), body: { expectedRouteRevision: 2 } })).rejects.toMatchObject({ status: 409, messageKey: "learning.feedbackRequired" });
      expect((await tx.query("SELECT id FROM unfurl.attempts WHERE enrollment_id=$1", [program.enrollmentId])).rowCount).toBe(0);
      expect((await tx.query("SELECT lesson_id FROM unfurl.enrollment_lesson_traversal WHERE enrollment_id=$1", [program.enrollmentId])).rowCount).toBe(1);
      await expect(service.revisit(actor, program.enrollmentId, { key: key(), body: { expectedRouteRevision: 2, lessonId: program.lessons[1]!.id, taskId: task.id } })).rejects.toMatchObject({ status: 403 });
      const revisitKey = key();
      const revisitBody = { expectedRouteRevision: 2, lessonId: program.lessons[0]!.id, taskId: null };
      const revisited = await service.revisit(actor, program.enrollmentId, { key: revisitKey, body: revisitBody });
      expect(revisited.data.route.next[0]).toMatchObject({ reasonCode: "scheduled_review", lessonId: program.lessons[0]!.id, taskId: null });
      expect(revisited.data.route.next[1]?.taskId).toBe(task.id);
      expect(revisited.data.enrollment.routeRevision).toBe(3);
      const replayedRevisit = await service.revisit(actor, program.enrollmentId, { key: revisitKey, body: revisitBody });
      expect(replayedRevisit.data.route.next).toEqual(revisited.data.route.next);
      await expect(service.revisit(actor, program.enrollmentId, { key: key(), body: { ...revisitBody, expectedRouteRevision: 3 } })).rejects.toMatchObject({ status: 409 });
      const returned = await service.advance(actor, program.enrollmentId, { key: key(), body: { expectedRouteRevision: 3 } });
      expect(returned.data.enrollment.routeRevision).toBe(4);
      expect(returned.data.task?.id).toBe(task.id);
      expect(returned.data.savedInput).toEqual(loaded.savedInput);
      expect(returned.data.activity?.events).toEqual(loaded.activity.events);
      expect((await tx.query("SELECT lesson_id FROM unfurl.enrollment_lesson_traversal WHERE enrollment_id=$1", [program.enrollmentId])).rowCount).toBe(1);
    });
  }, 90_000);
});
